import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from '../webui/web/node_modules/esbuild/lib/main.js';
const { chromium } = await import(process.env.NFQWS_PLAYWRIGHT_MODULE || 'playwright');
const web = fileURLToPath(new URL('../webui/web/', import.meta.url));
const dir = await mkdtemp(join(tmpdir(), 'blob-picker-ui-'));
let browser, server;
try {
  await build({ stdin: { resolveDir: web, loader: 'tsx', contents: `
    import React,{useRef,useState} from 'react';import{createRoot}from'react-dom/client';
    import{BlobPicker}from'./src/components/BlobPicker';import{TranslationContext}from'./src/context/TranslationContext';
    import ru from'./src/translations/ru.json';import en from'./src/translations/en.json';
    const lang=new URLSearchParams(location.search).get('lang')==='en'?'en':'ru',pack=lang==='en'?en:ru;
    const initial='--debug=0  --blob=tls:@/opt/etc/nfqws2/blobs/old.bin\\n--blob quic:@/opt/etc/nfqws2/blobs/quic.bin --lua-desync=fake:blob=tls';
    const t=(k,p={})=>(k.split('.').reduce((v,k)=>v?.[k],pack)||k).replace(/{{(\\w+)}}/g,(_,k)=>String(p[k]??k));
    function Fixture(){const[value,setValue]=useState(initial);const current=useRef(initial);const edit=v=>{current.current=v;setValue(v)};
      return <TranslationContext.Provider value={{t,langcode:lang,setLanguage(){}}}><BlobPicker value={value} getValue={()=>current.current} onChange={edit}/><textarea aria-label='Draft' value={value} onChange={e=>edit(e.target.value)}/><button onClick={()=>edit(initial)}>Reset fixture</button><button onClick={()=>fetch('/saved',{method:'POST',body:current.current})}>Save fixture</button></TranslationContext.Provider>}
    createRoot(document.getElementById('root')).render(<Fixture/>);
  ` }, bundle: true, platform: 'browser', format: 'iife', outfile: join(dir, 'fixture.js'), jsx: 'automatic', logLevel: 'silent', tsconfig: join(web, 'tsconfig.app.json'), plugins: [{ name: 'status-boundary', setup(b) { b.onLoad({ filter: /hooks\/useStatus\.tsx$/ }, () => ({ contents: 'export const useStatus=()=>({csrfToken:"fixture-csrf"});', loader: 'tsx' })); } }] });
  const script = await readFile(join(dir, 'fixture.js'));
  server = createServer((req, res) => { res.setHeader('Content-Type', req.url === '/fixture.js' ? 'text/javascript' : 'text/html'); res.end(req.url === '/fixture.js' ? script : '<!doctype html><html><body><div id="root"></div><script src="/fixture.js"></script></body></html>'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({ headless: true, ...(process.env.NFQWS_CHROMIUM_EXECUTABLE ? { executablePath: process.env.NFQWS_CHROMIUM_EXECUTABLE } : {}) });
  const page = await browser.newPage(); page.setDefaultTimeout(5000);
  const base = `http://127.0.0.1:${server.address().port}`;
  const bytes = Buffer.from([0, 255, 128, 10, 13, 1, 254]);
  const hash = createHash('sha256').update(bytes).digest('hex');
  const file = (name, format = 'tls') => ({ name, path: '/opt/etc/nfqws2/blobs/' + name, byte_length: 7, sha256: hash, state: 'available', format, label: { ru: 'Шаблон «пример»', en: 'Example template' }, bundled: true });
  const calls = [], uploads = [], saves = [];
  let failUpload = false, failInventory = false;
  await page.route('**/index.php', async route => {
    const post = Object.fromEntries(new URLSearchParams(route.request().postData())); calls.push(post.cmd);
    assert.equal(post.csrf_token, 'fixture-csrf');
    let body, status = 200;
    if (post.cmd === 'blobinventory') { if (failInventory) { status = 503; body = { error: 'resource_unavailable' }; } else body = { files: [file('old.bin'), file('other.bin'), file('quic.bin', 'quic')], skipped: 0, scan_truncated: false }; }
    else if (post.cmd === 'blobupload') { uploads.push(post); if (failUpload) { status = 409; body = { error: 'busy' }; } else body = { file: { ...file('device.bin', 'other'), bundled: false } }; }
    else throw new Error('Unexpected config/service request: ' + post.cmd);
    await route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) });
  });
  await page.route('**/saved', async route => { saves.push(route.request().postData()); await route.fulfill({ body: '{}' }); });
  await page.goto(base);
  assert.deepEqual(calls, [], 'Inventory is lazy');
  await page.getByText('Блоб — готовый шаблон данных для обхода блокировок. Если сайт, видео или звонок не работают, можно попробовать другой шаблон, не меняя стратегию.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Шаблоны пакетов (blobs)', exact: true }).click();
  await page.getByText('Файлов на роутере: 3', { exact: true }).waitFor();
  if (process.env.NFQWS_BLOB_SCREENSHOT) await page.screenshot({ path: process.env.NFQWS_BLOB_SCREENSHOT });
  const draft = page.getByRole('textbox', { name: 'Draft', exact: true });
  const original = await draft.inputValue();
  const selects = page.getByRole('combobox'); assert.equal(await selects.count(), 2);
  assert.equal(await selects.nth(0).inputValue(), '/opt/etc/nfqws2/blobs/old.bin');
  assert.equal(await selects.nth(1).inputValue(), '/opt/etc/nfqws2/blobs/quic.bin');
  await selects.nth(0).selectOption('/opt/etc/nfqws2/blobs/other.bin');
  const selected = original.replace('blobs/old.bin', 'blobs/other.bin'); assert.equal(await draft.inputValue(), selected);
  assert.deepEqual(calls, ['blobinventory']); assert.deepEqual(saves, []);
  await page.locator('input[type=file]').setInputFiles({ name: 'Файл с телефона.bin', mimeType: 'application/octet-stream', buffer: bytes });
  await page.getByText(/device\.bin.*выберите/i).waitFor();
  assert.equal(await draft.inputValue(), selected, 'Upload never assigns one of multiple bindings');
  assert.equal(uploads[0].name, 'Файл с телефона.bin'); assert.equal(uploads[0].sha256, hash); assert.equal(uploads[0].data_base64, 'AP+ACg0B/g==');
  await selects.nth(0).selectOption('/opt/etc/nfqws2/blobs/device.bin');
  assert.equal(await draft.inputValue(), original.replace('blobs/old.bin', 'blobs/device.bin'));
  assert.equal(await selects.nth(1).inputValue(), '/opt/etc/nfqws2/blobs/quic.bin', 'TLS change does not automatically replace QUIC');
  await page.getByRole('button', { name: 'Save fixture', exact: true }).click();
  await page.waitForResponse(r => r.url().endsWith('/saved')); assert.equal(saves[0], await draft.inputValue());
  failUpload = true;
  const beforeFailure = await draft.inputValue();
  await page.locator('input[type=file]').setInputFiles({ name: 'busy.bin', mimeType: '', buffer: bytes });
  await page.getByRole('alert').filter({ hasText: /занята/i }).waitFor();
  assert.equal(await draft.inputValue(), beforeFailure);
  await selects.nth(0).selectOption('/opt/etc/nfqws2/blobs/other.bin');
  assert.equal(await page.getByRole('alert').count(), 0, 'New selection clears an earlier upload error');
  await page.getByRole('button', { name: 'Reset fixture', exact: true }).click();
  assert.equal(await selects.nth(0).inputValue(), '/opt/etc/nfqws2/blobs/old.bin', 'External reset refreshes current selection');
  await draft.fill('--debug=2 --blob=tls:@/etc/nfqws2/blobs/manual.bin');
  assert.equal(await selects.count(), 1); assert.equal(await selects.first().inputValue(), '/etc/nfqws2/blobs/manual.bin', 'Raw edits refresh current selection without losing them');
  assert.ok(calls.every(c => ['blobinventory', 'blobupload'].includes(c)));
  await page.goto(base + '/?lang=en');
  await page.getByRole('button', { name: 'Packet templates (blobs)', exact: true }).click();
  await page.getByRole('button', { name: 'Upload from device', exact: true }).waitFor();
  await page.getByText('Files on router: 3', { exact: true }).waitFor();
  assert.match(await page.getByRole('combobox').first().textContent(), /Example template.*other\.bin.*TLS/);
  failInventory = true; failUpload = false;
  await page.goto(base);
  await page.getByRole('button', { name: 'Шаблоны пакетов (blobs)', exact: true }).click();
  await page.getByRole('alert').waitFor();
  await page.locator('input[type=file]').setInputFiles({ name: 'device.bin', mimeType: '', buffer: bytes });
  await page.getByText('Показано файлов: 1', { exact: true }).waitFor();
  await page.getByText(/device\.bin.*выберите/i).waitFor();
  assert.equal(await draft.inputValue(), original);
  console.log('PASS real BlobPicker RU/EN: lazy count/current/help, exact binary device upload, independent draft selection/reset/manual edits, errors preserve form and only explicit Save applies');
} finally { await browser?.close(); if (server) await new Promise(resolve => server.close(resolve)); await rm(dir, { recursive: true, force: true }); }

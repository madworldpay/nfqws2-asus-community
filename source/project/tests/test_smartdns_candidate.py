"""Real foreground child + real DNS helper: lifecycle, ports and byte limits."""
import json
import os
from pathlib import Path
import socket
import subprocess
import tempfile
import unittest
from test_dpi_normalize import PHP,PUBLIC,ROOT


class SmartDnsCandidateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp=tempfile.TemporaryDirectory();cls.probe=Path(cls.temp.name)/'probe'
        p=subprocess.run(['gcc','-Os','-nostdlib','-static','-fno-builtin','-fno-stack-protector','-fno-pie','-no-pie',str(ROOT/'asus/smartdns/dns-probe.c'),'-o',str(cls.probe)],capture_output=True,text=True)
        if p.returncode:raise AssertionError(p.stderr)
    @classmethod
    def tearDownClass(cls):cls.temp.cleanup()

    def exercise(self,mode='ready',port=16053):
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);bundle=root/'bundle';bundle.mkdir();marker=root/'engine-pid'
            # This fixture tests process ownership, not SmartDNS's algorithm;
            # routing semantics use the separately pinned real SmartDNS test.
            engine=bundle/'smartdns'
            engine.write_text(f'''#!/usr/bin/python3
import os,re,signal,socket,struct,sys,time
from pathlib import Path
Path({str(marker)!r}).write_text(str(os.getpid()))
if {mode!r}=='flood':
 while True:os.write(1,b'x'*4096)
if {mode!r}=='hang':
 signal.signal(signal.SIGTERM,signal.SIG_IGN)
 while True:time.sleep(1)
config=Path(sys.argv[sys.argv.index('-c')+1]).read_text()
port=int(re.search(r'^bind 127.0.0.1:([0-9]+)',config,re.M).group(1))
s=socket.socket(socket.AF_INET,socket.SOCK_DGRAM);s.bind(('127.0.0.1',port))
t=socket.socket(socket.AF_INET,socket.SOCK_STREAM);t.bind(('127.0.0.1',port));t.listen(2)
while True:
 q,peer=s.recvfrom(4096);typ=struct.unpack('!H',q[-4:-2])[0]
 answer=socket.inet_pton(socket.AF_INET6,'2001:db8::1') if typ==28 else socket.inet_aton('192.0.2.1')
 r=q[:2]+struct.pack('!HHHHH',0x8180,1,1,0,0)+q[12:]+b'\\xc0\\x0c'+struct.pack('!HHIH',typ,1,60,len(answer))+answer
 s.sendto(r,peer)
''');engine.chmod(0o700)
            probe=self.probe
            if mode=='serial':
                probe=root/'serial-probe'
                probe.write_text(f'''#!/usr/bin/python3
import fcntl,json,subprocess,sys,time
with open({str(root/'probe.lock')!r},'w') as lock:
 try:fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
 except BlockingIOError:
  print(json.dumps({{'error':'concurrent_probe'}}));sys.exit(71)
 time.sleep(.15)
 result=subprocess.run([{str(self.probe)!r},*sys.argv[1:]],capture_output=True)
 sys.stdout.buffer.write(result.stdout);sys.exit(result.returncode)
''');probe.chmod(0o700)
            candidate=PUBLIC/'smartdns-candidate.php'
            if mode=='early_exit':
                # Schedule the real child to finish before its first status
                # read. PHP 8.2 consumes that exit status only once.
                source=candidate.read_text().replace('__DIR__',json.dumps(str(PUBLIC),ensure_ascii=False))
                source=source.replace('        foreach ($pipes as $pipe) stream_set_blocking($pipe,false);', '        usleep(200000);foreach ($pipes as $pipe) stream_set_blocking($pipe,false);')
                candidate=root/'candidate.php';candidate.write_text(source)
            code=r'''$f=$argv[4];
            if(!is_file($f)){echo json_encode(['error'=>'missing_native_candidate']);exit;}
            require $f;$v=json_decode(stream_get_contents(STDIN),true);$now=(float)explode(' ',file_get_contents('/proc/uptime'))[0];
            $deps=['root'=>$argv[2].'/state','owner'=>(int)$argv[3],'bundle'=>fn()=>$argv[2].'/bundle','probe'=>fn()=>$v['probe']];
            if($v['mode']!=='no_guard')$deps['guard']=fn()=>true;
            $request=['request_id'=>str_repeat('b',32),'profile_hash'=>str_repeat('a',64),'stage'=>'profile','server_id'=>null,'bundle'=>$argv[2].'/bundle',
              'port'=>$v['port'],'config'=>"# Generated by NFQWS2 ASUS Community\nbind 127.0.0.1:".$v['port']."\n",'names'=>['example.org'],'query_timeout_ms'=>2500,'max_parallel_queries'=>2,'deadline_uptime'=>$now+($v['mode']==='hang'?0.5:5)];
            if($v['mode']==='wrong_bundle')$request['bundle']='/untrusted';
            if($v['mode']==='bad_hash')$request['profile_hash']=[];
            if($v['mode']==='bad_bundle')$request['bundle']=[];
            try{$out=(new AsusSmartDnsCandidate(new AsusSmartDnsInstaller(),str_repeat('b',32),$deps))->run($request);}
            catch(Throwable $e){$out=['error'=>$e->getMessage()];}echo json_encode($out);'''
            p=subprocess.run([PHP,'-n','-r',code,str(PUBLIC),str(root),str(os.getuid()),str(candidate)],input=json.dumps({'mode':mode,'port':port,'probe':str(probe)}),capture_output=True,text=True,timeout=10)
            self.assertEqual(p.returncode,0,p.stdout+p.stderr);self.assertEqual(p.stderr,'')
            if marker.exists():
                pid=int(marker.read_text());stat=Path(f'/proc/{pid}/stat')
                self.assertFalse(stat.exists(),'candidate orphaned after PHP returned')
            return json.loads(p.stdout),marker.exists()

    def test_real_dns_helpers_read_the_candidate_and_all_children_are_reaped(self):
        value,started=self.exercise();self.assertTrue(started)
        self.assertNotIn('error',value);self.assertTrue(value['started']);self.assertTrue(value['syntax_ok'])
        self.assertEqual([x['type'] for x in value['results']],['A','AAAA'])
        self.assertTrue(all(x['udp']['ok'] for x in value['results']))

    def test_unmanaged_php_process_cannot_start_an_engine(self):
        value,started=self.exercise('no_guard');self.assertEqual(value,{'error':'guard_unavailable'});self.assertFalse(started)

    def test_address_family_probes_do_not_overlap_process_reservations(self):
        value,started=self.exercise('serial');self.assertTrue(started)
        self.assertNotIn('error',value)
        self.assertEqual([x['type'] for x in value['results']],['A','AAAA'])

    def test_fast_child_exit_is_kept_from_the_first_process_status_read(self):
        value,started=self.exercise('early_exit');self.assertTrue(started)
        self.assertNotIn('error',value)
        self.assertTrue(all(row['udp']['ok'] for row in value['results']))

    def test_timeout_kills_a_child_that_ignores_term(self):
        value,started=self.exercise('hang');self.assertTrue(started);self.assertEqual(value,{'error':'timed_out'})

    def test_output_flood_is_bounded_and_reaped(self):
        value,started=self.exercise('flood');self.assertTrue(started);self.assertEqual(value,{'error':'output_limit'})

    def test_foreign_port_is_not_killed_or_adopted(self):
        with socket.socket(socket.AF_INET,socket.SOCK_DGRAM) as foreign:
            foreign.bind(('127.0.0.1',16053))
            value,started=self.exercise();self.assertEqual(value,{'error':'port_busy'});self.assertFalse(started)
            foreign.getsockname()

    def test_caller_cannot_choose_a_different_engine_directory(self):
        value,started=self.exercise('wrong_bundle');self.assertEqual(value,{'error':'invalid_state'});self.assertFalse(started)

    def test_wrong_request_types_have_a_fixed_error_and_start_nothing(self):
        for mode in ['bad_hash','bad_bundle']:
            with self.subTest(mode=mode):
                value,started=self.exercise(mode);self.assertEqual(value,{'error':'invalid_request'});self.assertFalse(started)


if __name__=='__main__':unittest.main()
